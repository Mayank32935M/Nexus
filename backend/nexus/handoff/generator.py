import json
import re
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from nexus.config import settings
from nexus.core.database import get_db_connection, log_audit_event
from nexus.memory.vault import MemoryVault
from nexus.memory.indexer import VaultIndexer


class HandoffGenerator:
    """Generates structured, lossless AI session handoff documents between human and models."""

    def __init__(self, vault: Optional[MemoryVault] = None, db_path: Optional[Path] = None):
        self.vault = vault or MemoryVault()
        self.db_path = db_path or settings.nexus_db_path
        self.indexer = VaultIndexer(self.vault, self.db_path)

    def generate_handoff(
        self,
        session_title: str,
        target_model: str,
        current_goal: str,
        completed_work: List[str],
        decisions_made: List[str],
        next_steps: List[str],
        project_name: Optional[str] = None,
        open_questions: Optional[List[str]] = None,
        context_files: Optional[List[str]] = None,
        agent: str = "human-operator",
    ) -> Dict[str, Any]:
        """
        Generates a comprehensive AI session handoff document and stores it in AI-HANDOFF/.
        """
        now = datetime.now(timezone.utc)
        date_str = now.strftime("%Y-%m-%d")
        timestamp_slug = now.strftime("%Y%m%d_%H%M%S")
        clean_slug = re.sub(r'[^a-zA-Z0-9_\-]', '_', session_title.lower()).strip('_')[:30]
        
        proj_prefix = f"{project_name.upper()}_" if project_name else ""
        filename = f"{date_str}_{proj_prefix}{clean_slug or 'session'}.md"
        rel_path = f"AI-HANDOFF/{filename}"

        # Load context files if requested
        context_sections = []
        if context_files:
            for cp in context_files:
                try:
                    f_info = self.vault.read_file(cp)
                    context_sections.append(f"### Context: {cp}\n```markdown\n{f_info['content']}\n```")
                except Exception:
                    pass

        # Format items
        completed_md = "\n".join([f"- [x] {item}" for item in completed_work]) or "- None recorded."
        decisions_md = "\n".join([f"- **ADR**: {item}" for item in decisions_made]) or "- None recorded."
        next_steps_md = "\n".join([f"- [ ] {item}" for item in next_steps]) or "- [ ] Continue next implementation step."
        questions_md = "\n".join([f"- ? {item}" for item in (open_questions or [])]) or "- None currently pending."
        contexts_md = "\n\n".join(context_sections) or "No additional file payloads embedded."

        handoff_content = f"""---
title: "AI Session Handoff: {session_title}"
target_model: {target_model}
project: {project_name or "GENERAL"}
date: {date_str}
created_at: {now.isoformat()}
author: {agent}
tags: [handoff, {target_model.lower()}, session]
---

# AI Session Handoff — {session_title}

> **Target Model**: `{target_model}`  
> **Source Agent**: `{agent}`  
> **Project**: `{project_name or 'GENERAL'}`  
> **Timestamp**: `{now.isoformat()}`  

---

## 1. Primary Session Goal & Mission
{current_goal}

---

## 2. Completed Work & Verified Items
{completed_md}

---

## 3. Key Decisions & Architectural Rationale
{decisions_md}

---

## 4. Pending Open Questions & Edge Cases
{questions_md}

---

## 5. Immediate Next Steps for Receiving Agent
{next_steps_md}

---

## 6. Attached Vault Context
{contexts_md}

---
*Generated by NEXUS Personal AI Intelligence Ecosystem*
"""

        # Write to vault
        self.vault.write_file(rel_path, handoff_content, agent=agent, bypass_approval_check=True)
        self.indexer.index_single_file(rel_path)

        # Record in SQLite sessions table
        session_id = str(uuid.uuid4())
        conn = get_db_connection(self.db_path)
        try:
            cursor = conn.cursor()
            cursor.execute(
                """
                INSERT INTO sessions (id, title, agent, target_model, summary, created_at, metadata)
                VALUES (?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    session_id,
                    session_title,
                    agent,
                    target_model,
                    current_goal,
                    now.isoformat(),
                    json.dumps({
                        "file_path": rel_path,
                        "project": project_name,
                        "completed_count": len(completed_work),
                        "next_steps_count": len(next_steps),
                    }),
                ),
            )
            conn.commit()

            log_audit_event(
                event_type="HANDOFF_GENERATED",
                file_path=rel_path,
                agent=agent,
                details={"target_model": target_model, "session_title": session_title},
                db_path=self.db_path,
            )
        finally:
            conn.close()

        return {
            "session_id": session_id,
            "title": session_title,
            "target_model": target_model,
            "file_path": rel_path,
            "content": handoff_content,
            "created_at": now.isoformat(),
        }

    def list_sessions(self, limit: int = 30) -> List[Dict[str, Any]]:
        """Lists historical sessions and handoffs."""
        conn = get_db_connection(self.db_path)
        try:
            cursor = conn.cursor()
            cursor.execute(
                """
                SELECT id, title, agent, target_model, summary, created_at, metadata
                FROM sessions
                ORDER BY created_at DESC
                LIMIT ?
                """,
                (limit,),
            )
            rows = cursor.fetchall()
            results = []
            for r in rows:
                meta = json.loads(r["metadata"]) if r["metadata"] else {}
                results.append({
                    "id": r["id"],
                    "title": r["title"],
                    "agent": r["agent"],
                    "target_model": r["target_model"],
                    "summary": r["summary"],
                    "created_at": r["created_at"],
                    "file_path": meta.get("file_path"),
                    "project": meta.get("project"),
                })
            return results
        finally:
            conn.close()

